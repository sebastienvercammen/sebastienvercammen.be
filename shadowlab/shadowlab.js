/* Which side a line leaves by is decided by the layout, not by the geometry of the two boxes. The
   gutters between the columns and the gaps between stacked cards are the only card-free space on
   the stage, so a line between two columns leaves through the facing vertical sides and travels
   the gutter, and a line inside a column leaves through the facing horizontal ones. Picking the
   side from the deltas instead sent facts-placements out through the top of facts and straight
   under visits, because the vertical delta was the larger one. */
function erdAnchor(ta, tb) {
  const a = erdBox(ta), b = erdBox(tb);
  if (ERD_AT[ta] === ERD_AT[tb])
    return b.y > a.y ? [a.x + a.w / 2, a.y + a.h, 0, 1] : [a.x + a.w / 2, a.y, 0, -1];
  return b.x > a.x ? [a.x + a.w, a.y + a.h / 2, 1, 0] : [a.x, a.y + a.h / 2, -1, 0];
}

function erdBox(t) {
  const c = erdCard(t);
  return {x: parseFloat(c.style.left), y: parseFloat(c.style.top), w: c.offsetWidth, h: c.offsetHeight};
}

function erdLayout() {
  const gap = 34;
  const hs = ERD_COLS.map((c) => c.of.reduce((s, t) => s + erdCard(t).offsetHeight + gap, -gap));
  erd.h = Math.max(...hs);
  ERD_COLS.forEach((c, i) => {
    let y = (erd.h - hs[i]) / 2;
    for (const t of c.of) {
      const card = erdCard(t);
      card.style.left = c.x + 'px';
      card.style.top = Math.round(y) + 'px';
      y += card.offsetHeight + gap;
    }
  });
  $('#schema').style.height = erd.h + 'px';
}

function erdPaint() {
  const svg = $('.erd-edges');
  svg.setAttribute('viewBox', '0 0 ' + ERD_W + ' ' + erd.h);
  svg.style.width = ERD_W + 'px';
  svg.style.height = erd.h + 'px';
  svg.textContent = '';
  const seg = ERD_LINKS.filter(([, , k]) => !erd.off.has(k))
    .map(([ta, tb, k, lbl]) => ({ta, tb, k, lbl, a: erdAnchor(ta, tb), b: erdAnchor(tb, ta)}));
  /* Three joins leave the right-hand side of facts. On one anchor they would start from the same
     point in a bundle you cannot trace a single line through, so each side spreads its own lines
     along itself, in the order of the boxes at the far end - which also keeps them from crossing
     each other on the way out. */
  const sides = {};
  for (const s of seg) for (const e of ['a', 'b']) {
    const key = (e === 'a' ? s.ta : s.tb) + s[e][2] + ',' + s[e][3];
    (sides[key] = sides[key] || []).push({s, e, far: e === 'a' ? s.tb : s.ta});
  }
  for (const g of Object.values(sides)) {
    if (g.length < 2) continue;
    const vert = g[0].s[g[0].e][2] !== 0;
    const box = erdBox(g[0].e === 'a' ? g[0].s.ta : g[0].s.tb);
    const step = Math.min(26, (vert ? box.h : box.w) / g.length);
    g.sort((p, q) => (vert ? erdBox(p.far).y - erdBox(q.far).y : erdBox(p.far).x - erdBox(q.far).x));
    g.forEach((p, i) => { p.s[p.e][vert ? 1 : 0] += (i - (g.length - 1) / 2) * step; });
  }
  for (const {ta, tb, k, lbl, a: [ax, ay, anx, any], b: [bx, by, bnx, bny]} of seg) {
    /* The bend is taken along the direction the line leaves by, not from the distance between the
       two points. Two boxes a long way apart vertically but nearly touching horizontally have a
       large separation and a tiny horizontal gap, and a control point sized on the former lands
       past its opposite number - which draws a loop, not a curve. The 0.45 keeps the two control
       points on their own halves of a 70px gutter or a 34px gap, so the curve stays in it. */
    const ba = Math.max(12, Math.min(Math.abs(anx ? bx - ax : by - ay) * 0.45, 160));
    const bb = Math.max(12, Math.min(Math.abs(bnx ? bx - ax : by - ay) * 0.45, 160));
    const near = erd.focus === ta || erd.focus === tb;
    const p = sv('path');
    p.setAttribute('d', 'M' + ax + ' ' + ay + 'C' + (ax + anx * ba) + ' ' + (ay + any * ba)
      + ' ' + (bx + bnx * bb) + ' ' + (by + bny * bb) + ' ' + bx + ' ' + by);
    p.setAttribute('class', 'e ' + erdKind(k) + (lbl ? ' bit' : '')
      + (!erd.focus ? '' : near ? ' on' : ' off'));
    svg.append(p);
    /* The key is named on the line only while a table is focused. Eight labels at once is a
       diagram you have to read instead of look at, and the colour already says which key. */
    if (near) {
      const lab = sv('text');
      /* Clear of the line, not on it. Both numbers come off the CURVE, not off the straight line
         between the two anchors: an S-curve leaves its own chord, so a label placed against the
         chord can sit right on the line it is labelling. Above the curve where the curve is running
         across at that point, beside it where it is running down. */
      const L = p.getTotalLength();
      const m = p.getPointAtLength(L / 2), m2 = p.getPointAtLength(Math.min(L, L / 2 + 6));
      const steep = Math.abs(m2.y - m.y) > Math.abs(m2.x - m.x);
      lab.setAttribute('x', m.x + (steep ? 9 : 0));
      lab.setAttribute('y', m.y - (steep ? 0 : 8));
      /* Inline style, not the attribute: .erd-edges text sets text-anchor in the stylesheet, and
         a CSS rule outranks a presentation attribute however specific the attribute looks. */
      if (steep) lab.style.textAnchor = 'start';
      lab.setAttribute('class', 'el ' + erdKind(k));
      lab.textContent = lbl || k;
      svg.append(lab);
    }
  }
}

function erdNote() {
  const n = $('#erd-note');
  if (!erd.focus) {
    /* 'links', not 'joins': one of them is the bit test, and counting it as a join would be
       the diagram telling the reader something it also draws as untrue. */
    n.textContent = SCHEMA.length + ' tables · ' + ERD_LINKS.length + ' links';
    return;
  }
  const js = ERD_LINKS.filter(([a, b]) => a === erd.focus || b === erd.focus)
    .map(([a, b, k, lbl]) => (a === erd.focus ? b : a) + (lbl ? ' via ' : ' on ') + (lbl || k));
  n.textContent = erd.focus + ' · ' + js.join(' · ');
}

function erdFocus(t) {
  erd.focus = t;
  const near = new Set();
  if (t) for (const [a, b] of ERD_LINKS) { if (a === t) near.add(b); if (b === t) near.add(a); }
  for (const c of document.querySelectorAll('#schema .schema-card')) {
    c.classList.toggle('on', c.dataset.t === t);
    c.classList.toggle('far', !!t && c.dataset.t !== t && !near.has(c.dataset.t));
  }
  erdPaint();
  erdNote();
}

