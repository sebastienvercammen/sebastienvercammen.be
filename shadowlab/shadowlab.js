/* ---- the atlas canvas ----------------------------------------------------
   Each cascade is a 2048-square drawn into a 512-square panel, three side by
   side, which is the atlas layout at its real relative scale. The uv values in
   the table are the raw unclamped projection, so drawing clamps to the unit
   square exactly the way the residency flags do. */
const ATLAS_SQL = `-- every projection that lands inside its cascade, in walk order
SELECT f.caster_uid,
       f.cascade,
       f.atlas_u0, f.atlas_v0, f.atlas_u1, f.atlas_v1,
       f.depth_min, f.depth_max,
       f.world_cx, f.world_cy, f.world_cz,
       f.world_hx, f.world_hy, f.world_hz,
       f.foot_texels,
       f.clipped,
       coalesce(m.tri_count, 0)                 AS tri_count,
       coalesce(max(v.enrolled), -1)            AS enrolled
FROM facts f
LEFT JOIN meshes m USING (caster_uid)
LEFT JOIN visits v USING (caster_uid)
WHERE f.outside = 0
GROUP BY ALL
ORDER BY f.caster_uid, f.cascade;`;

const RAMP = [[10, 14, 19], [22, 62, 78], [31, 120, 130], [79, 214, 188], [196, 246, 228], [255, 255, 255]];
/* RAMP runs dark-to-white in one hue, which is right for a filled density field and wrong for
   wireframe: a 1px antialiased line loses most of its brightness to the background, so two
   steps that differ only in luminance read as the same colour. This one moves through hue
   instead, which survives being thin. */
const TRIRAMP = [[60, 92, 214], [38, 176, 214], [86, 214, 122], [232, 216, 78], [244, 148, 54], [232, 68, 68]];
function ramp(t) {
  t = Math.max(0, Math.min(1, t)) * (RAMP.length - 1);
  const i = Math.min(RAMP.length - 2, Math.floor(t)), f = t - i;
  const a = RAMP[i], b = RAMP[i + 1];
  return 'rgb(' + Math.round(a[0] + (b[0] - a[0]) * f) + ',' + Math.round(a[1] + (b[1] - a[1]) * f) + ',' + Math.round(a[2] + (b[2] - a[2]) * f) + ')';
}

let atlasRows = [];
let atlasMode = 'overdraw';
let atlasFill = 'fill';
let atlasPlaying = 0;

/* A box in canvas pixels, clamped to its own cascade panel. The uv values in the table are the
   raw unclamped projection, so this clamps exactly the way the residency flags do. */
function boxPx(r, S) {
  const c = r.cascade;
  const u0 = Math.max(0, Math.min(1, r.atlas_u0)), u1 = Math.max(0, Math.min(1, r.atlas_u1));
  const v0 = Math.max(0, Math.min(1, r.atlas_v0)), v1 = Math.max(0, Math.min(1, r.atlas_v1));
  return [c * S + u0 * S, v0 * S, c * S + u1 * S, v1 * S];
}

function rampRGB(t, R = RAMP) {
  t = Math.max(0, Math.min(1, t)) * (R.length - 1);
  const i = Math.min(R.length - 2, Math.floor(t)), f = t - i;
  const a = R[i], b = R[i + 1];
  return [a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f, a[2] + (b[2] - a[2]) * f];
}

/* Overlap is counted exactly rather than approximated with additive alpha. Alpha saturates - a
   handful of casters clamp to a whole cascade, so at any usable opacity every texel reached full
   brightness and the structure vanished into white. This accumulates a real per-texel count with
   a 2D difference array plus two prefix sums, which is O(boxes + pixels) no matter how large the
   boxes are, and then maps the count through a log ramp. The number in the legend is the actual
   maximum, so the picture is a measurement instead of an impression. */
function overlapField(shown, W, H, S) {
  const acc = new Int32Array((W + 1) * (H + 1));
  for (const r of shown) {
    const b = boxPx(r, S);
    const x0 = Math.floor(b[0]), y0 = Math.floor(b[1]);
    const x1 = Math.min(W, Math.max(x0 + 1, Math.ceil(b[2])));
    const y1 = Math.min(H, Math.max(y0 + 1, Math.ceil(b[3])));
    acc[y0 * (W + 1) + x0]++; acc[y0 * (W + 1) + x1]--;
    acc[y1 * (W + 1) + x0]--; acc[y1 * (W + 1) + x1]++;
  }
  for (let y = 0; y <= H; y++) { let run = 0; for (let x = 0; x <= W; x++) { run += acc[y * (W + 1) + x]; acc[y * (W + 1) + x] = run; } }
  for (let x = 0; x <= W; x++) { let run = 0; for (let y = 0; y <= H; y++) { run += acc[y * (W + 1) + x]; acc[y * (W + 1) + x] = run; } }
  let max = 0;
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) { const v = acc[y * (W + 1) + x]; if (v > max) max = v; }
  return {acc, max};
}

let atlasMaxOverlap = 0;
let atlasDepthLo = 0, atlasDepthHi = 1, atlasDepthOut = 0;
let atlasAreaVar = 'log';

function paintAtlas() {
  const cv = $('#atlas-canvas'), g = cv.getContext('2d');
  const S = cv.height, W = cv.width, H = cv.height, N = atlasRows.length;
  const upto = Math.round(N * Number($('#atlas-step').value) / 1000);
  const shown = atlasRows.slice(0, upto);
  g.globalCompositeOperation = 'source-over';
  g.fillStyle = '#070A0D';
  g.fillRect(0, 0, W, H);

  /* Ranges come from the whole result, not from the revealed slice, so the colour of a given
     box does not change as the slider moves. */
  const maxTri = Math.max(1, ...atlasRows.map((r) => r.tri_count || 0));
  const maxArea = Math.max(1, ...atlasRows.map((r) => r.foot_texels || 0));
  const dLo = atlasDepthLo, dHi = atlasDepthHi;

  /* Enrolment forces outlines: the boxes span five orders of magnitude in area and a single
     never-enrolled box clamped to a whole cascade covers the panel. The forcing is shown on the
     Draw control rather than applied to it, so the reader's own choice survives the mode change. */
  const forcedLine = atlasMode === 'enrol'
    || (atlasMode === 'area' && (atlasAreaVar === 'line' || atlasAreaVar === 'clip'));
  const fillNow = forcedLine ? 'line' : atlasFill;

  if (atlasMode === 'overdraw' && fillNow === 'fill' && shown.length) {
    const f = overlapField(shown, W, H, S);
    atlasMaxOverlap = f.max;
    const img = g.createImageData(W, H);
    const d = img.data, mx = Math.max(1, f.max);
    for (let y = 0; y < H; y++) {
      for (let x = 0; x < W; x++) {
        const c = f.acc[y * (W + 1) + x], o = (y * W + x) * 4;
        const rgb = c === 0 ? [7, 10, 13] : rampRGB(c / mx);
        d[o] = rgb[0]; d[o + 1] = rgb[1]; d[o + 2] = rgb[2]; d[o + 3] = 255;
      }
    }
    g.putImageData(img, 0, 0);
  } else {
    /* Largest first, so a terrain-sized box cannot bury every small caster behind it. In the
       enrolment view the sort is by category first: nearly everything is enrolled, so drawing
       that majority underneath is the only way the minority is visible at all. The legend says
       so - a draw order that changes what you notice has to be stated. */
    const rank = (r) => (r.enrolled === 1 ? 0 : (r.enrolled === -1 ? 1 : 2));
    const clipRank = (r) => (r.clipped ? 1 : 0);
    const cat = atlasMode === 'enrol' ? rank : (atlasMode === 'area' && atlasAreaVar === 'clip' ? clipRank : null);
    const order = shown.slice().sort((a, b) => (cat && cat(a) !== cat(b))
      ? cat(a) - cat(b)
      : (b.foot_texels || 0) - (a.foot_texels || 0));
    for (const r of order) {
      const b = boxPx(r, S);
      const pw = Math.max(0.7, b[2] - b[0]), ph = Math.max(0.7, b[3] - b[1]);
      let col;
      if (atlasMode === 'tris') col = ramp(Math.log1p(r.tri_count) / Math.log1p(maxTri));
      else if (atlasMode === 'area') {
        if (atlasAreaVar === 'rank') col = ramp(r.arank);
        else if (atlasAreaVar === 'clip') col = r.clipped ? 'rgba(224,138,74,.95)' : 'rgba(79,214,188,.30)';
        else col = ramp(Math.log1p(r.foot_texels) / Math.log1p(maxArea));
      }
      else if (atlasMode === 'depth') col = ramp(dHi > dLo ? (r.depth_min - dLo) / (dHi - dLo) : 0.5);
      else if (atlasMode === 'enrol') col = r.enrolled === 1 ? 'rgba(79,214,188,.42)' : (r.enrolled === 0 ? 'rgba(224,138,74,.95)' : 'rgba(150,163,177,.6)');
      else col = 'rgba(79,214,188,.16)';
      if (fillNow === 'fill') { g.fillStyle = col; g.fillRect(b[0], b[1], pw, ph); }
      else { g.strokeStyle = col; g.lineWidth = 0.7; g.strokeRect(b[0] + 0.5, b[1] + 0.5, pw, ph); }
    }
  }

  g.strokeStyle = 'rgba(232,238,244,.22)';
  g.lineWidth = 1;
  for (let c = 1; c < 3; c++) { g.beginPath(); g.moveTo(c * S, 0); g.lineTo(c * S, H); g.stroke(); }
  $('#atlas-step-lbl').textContent = fmt(upto) + ' of ' + fmt(N) + ' projections';
  syncFillSeg();
  drawAtlasLegend(maxTri, maxArea, dLo, dHi);
}

function syncFillSeg() {
  const seg = $('.seg[data-seg="fill"]');
  const forced = atlasMode === 'enrol'
    || (atlasMode === 'area' && (atlasAreaVar === 'line' || atlasAreaVar === 'clip'));
  const eff = forced ? 'line' : atlasFill;
  for (const o of seg.children) {
    o.classList.toggle('on', o.dataset.v === eff);
    o.classList.toggle('forced-off', forced && o.dataset.v === 'fill');
  }
  seg.classList.toggle('forced', forced);
  $('#fill-note').textContent = forced
    ? (atlasMode === 'enrol' ? 'outline forced by Enrolment' : 'outline forced by this candidate')
    : '';
  $('#area-ctl').hidden = atlasMode !== 'area';
}

