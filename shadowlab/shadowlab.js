const panels = [];

function buildPanel(host, spec) {
  host.innerHTML = '';
  const head = el('div', 'q-head');
  head.append(el('h4', null, spec.title));
  if (spec.sub) head.append(el('div', 'q-sub', spec.sub));
  const out = el('div', 'q-out empty', '');
  const det = el('details', 'q-sql');
  det.open = true;
  det.append(el('summary', null, 'SQL'));
  const edHost = el('div', 'q-ed');
  const bar = el('div', 'q-bar');
  const runBtn = el('button', 'btn primary', 'Run');
  const resetBtn = el('button', 'btn', 'Reset');
  const note = el('span', 'q-note', '');
  bar.append(runBtn, resetBtn, note);
  const tbl = el('div', 'q-table-host');
  det.append(edHost, bar, tbl);
  host.append(head, out, det);

  /* CodeMirror measures on construction, so it goes in after the host is in the
     document. viewportMargin Infinity renders every line, which is what lets the
     editor size itself to the query the way the textarea did. */
  const ed = CodeMirror(edHost, {
    value: spec.sql.trim(), mode: 'text/x-sql', theme: 'shadowlab',
    lineWrapping: false, matchBrackets: true, viewportMargin: Infinity,
    tabSize: 2, indentUnit: 2, extraKeys: {'Ctrl-Enter': () => panel.refresh(), 'Cmd-Enter': () => panel.refresh()},
  });

  /* A chart or a canvas reads columns by name and cannot survive an arbitrary result, so the
     figure runs the query this page shipped and stops listening to the editor. What the reader
     types goes to the table below, which takes any shape. Where the figure IS a table there is
     nothing to protect, so those panels stay live and skip the second copy. */
  let figured = false;

  const panel = {
    spec, out, ed, note, tbl,
    async refresh() {
      if (!conn) return;
      note.className = 'q-note';
      try {
        const r = await run(ed.getValue());
        if (spec.draw === drawTable) {
          drawTable(out, r);
          tbl.innerHTML = '';
        } else {
          drawTable(tbl, r);
          if (!figured) {
            /* First pass, the editor still holds the shipped query verbatim, so its result is
               the figure's result and running it twice would only cost the reader a download. */
            (spec.draw || drawBars)(out,
              ed.getValue().trim() === spec.sql.trim() ? r : await run(spec.sql), spec.opts);
            figured = true;
          }
        }
        note.textContent = fmt(r.rows.length) + ' rows · ' + r.ms.toFixed(1) + ' ms';
      } catch (e) {
        note.className = 'q-note err';
        note.textContent = String(e.message || e);
        tbl.innerHTML = '';
        if (spec.draw === drawTable) {
          out.className = 'q-out empty';
          out.textContent = 'query failed, see the message under the SQL';
        }
      }
    },
  };
  runBtn.addEventListener('click', () => panel.refresh());
  resetBtn.addEventListener('click', () => { ed.setValue(spec.sql.trim()); panel.refresh(); });
  /* A details element that starts open still reports zero height for anything
     built while it was closed, and the reader can collapse and reopen it. */
  det.addEventListener('toggle', () => { if (det.open) ed.refresh(); });
  panels.push(panel);
  return panel;
}

